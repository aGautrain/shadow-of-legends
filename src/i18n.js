export const STRINGS = { fr, en };

let current = DEFAULT_LANG;
export const lang = () => current;

// A supported language from a saved or requested value, else the default.
export const pickLang = (value) => (LANGS.includes(value) ? value : DEFAULT_LANG);
export function setLang(value) { current = pickLang(value); return current; }

// French treats 0 and 1 as singular, English only 1.
export const pluralForm = (l, n) => (l === 'fr' ? (Math.abs(n) < 2 ? 'one' : 'other') : (n === 1 ? 'one' : 'other'));

const LOCALE = { fr: 'fr-FR', en: 'en-US' };
// A number in the current language: "1,5" in French, "1.5" in English.
// No grouping, so game units read 3000 in both.
export function num(n, digits) {
  const opts = digits === undefined ? { maximumFractionDigits: 2 } : { minimumFractionDigits: digits, maximumFractionDigits: digits };
  return new Intl.NumberFormat(LOCALE[current], { useGrouping: false, ...opts }).format(n);
}

// The text for key in the current language, falling back to English, then the key.
export function t(key, params = {}) {
  let s = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  if (typeof s === 'object') s = s[pluralForm(current, params.n)] ?? s.other;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? (typeof params[k] === 'number' ? num(params[k]) : String(params[k])) : m));
}
